/// Generates LTX clips and writes them into the storyboard as blended inserts.
/// The clips are *mixed into* the demo (MUL/XOR/screen/etc.), not cut to, so a
/// failed or skipped LTX stage still leaves a complete video.
///
/// Two shapes, chosen by LtxSettings.Mode:
///
///   inserts     - a handful of clips spread over the loudest scenes, each one an
///                 event that arrives and leaves.
///   continuous  - whole scenes tiled end to end with short clips, concatenated
///                 into one file per scene, so the AI video runs underneath the
///                 effects for a stretch at a time.
///
/// Continuous is not a longer insert. Every clip still starts from the frame of
/// the demo it lands on, so a two-minute run never drifts away from what the
/// effects are doing - which is the only reason a permanent overlay reads as a
/// blend rather than as a video with a demo on top of it. Both shapes are planned
/// into the same Run/Slot pair below and generated by the same loop; sparse mode
/// is simply runs of one clip.
public sealed class LtxStage(
    Ffmpeg ffmpeg,
    string workflowDir,
    Func<double, int, int, CancellationToken, Task<byte[]>>? snapshot = null,
    EffectRegistry? effects = null)
{
    /// One clip to generate: where it lands, how long it lasts, what it shows.
    sealed record Slot(double Start, double Seconds, string Prompt, string Key);

    /// A stretch of the video covered end to end by clips, all inside one scene
    /// and mixed with one blend mode.
    sealed record Run(int Index, StoryScene Scene, List<Slot> Slots);

    /// A run, or the surviving part of one after a clip failed to generate: a
    /// single continuous piece of video and the span it occupies.
    sealed record Piece(int Run, StoryScene Scene, double Start, double Duration, string File);

    public async Task<Storyboard> RunAsync(
        ProjectPaths paths, ProjectSettings settings, AudioAnalysis analysis,
        Storyboard storyboard, IProgress<StageProgress> progress, CancellationToken ct)
    {
        var ltx = settings.Ltx;
        var (rw, rh) = settings.Resolution;
        // LTX wants multiples of 32, and generating at full output size is slow;
        // half size upscales fine because the clip is composited, not shown raw.
        int lw = RoundTo32(rw / 2), lh = RoundTo32(rh / 2);

        int frames = AlignFrames(ltx.ClipSeconds, settings.Fps);
        double clipLen = frames / (double)settings.Fps;

        var song = SongText.Parse(paths.FindTxt() is { } t ? File.ReadAllText(t) : null);

        var runs = ltx.Continuous
            ? PlanContinuous(storyboard, analysis, settings, song, clipLen, frames, lw, lh, progress)
            : PlanSparse(storyboard, analysis, settings, song, clipLen, frames, lw, lh, progress);

        int totalClips = runs.Sum(r => r.Slots.Count);
        if (totalClips == 0)
        {
            progress.Report(new StageProgress(PipelineStage.Ltx, 1.0, "No suitable insert points"));
            return storyboard;
        }

        Directory.CreateDirectory(paths.LtxDir);
        Directory.CreateDirectory(paths.KeyframeDir);
        var cache = LoadCache(paths);

        using var comfy = new ComfyClient(
            ltx.ComfyUrl, ltx.ComfyRoot, workflowDir,
            log => progress.Report(new StageProgress(PipelineStage.Ltx, 0, log)));

        var pieces = new List<Piece>();
        bool comfyUp = false;
        int ordinal = 0;

        foreach (var run in runs)
        {
            // A clip that fails splits its run rather than losing it: the stretches
            // either side are still continuous video, and each becomes its own
            // insert with its own fades.
            var made = new List<(string File, Slot Slot)>();

            void CloseSegment()
            {
                if (made.Count == 0) return;
                pieces.Add(new Piece(run.Index, run.Scene, made[0].Slot.Start,
                    made.Sum(m => m.Slot.Seconds), Concatenated(paths, settings, made, pieces.Count)));
                made.Clear();
            }

            // Only set when the previous clip of this run is on disk and the user
            // asked for the LTX video to carry its own motion forward.
            string? carryFrom = null;

            foreach (var slot in run.Slots)
            {
                ct.ThrowIfCancellationRequested();
                double frac = ordinal / (double)totalClips;
                int no = ++ordinal;

                try
                {
                    string file;
                    if (cache.TryGetValue(slot.Key, out var cached) && File.Exists(cached))
                    {
                        progress.Report(new StageProgress(PipelineStage.Ltx, frac,
                            $"clip {no}/{totalClips} - cached"));
                        file = cached;
                    }
                    else
                    {
                        if (!comfyUp) { await comfy.EnsureUpAsync(ct); comfyUp = true; }

                        progress.Report(new StageProgress(PipelineStage.Ltx, frac,
                            $"clip {no}/{totalClips} at {slot.Start:0.#}s - {Trunc(slot.Prompt, 60)}"));

                        file = await GenerateAsync(
                            comfy, paths, settings, song, slot, frames, lw, lh, no - 1, carryFrom, ct);
                        cache[slot.Key] = file;
                        SaveCache(paths, cache);
                    }

                    made.Add((file, slot));
                    carryFrom = ltx.Carry ? file : null;
                }
                catch (OperationCanceledException) { throw; }
                catch (Exception e)
                {
                    // One failed clip must not lose the other clips or the video.
                    progress.Report(new StageProgress(PipelineStage.Ltx, frac,
                        $"clip {no} failed, continuing without it: {Trunc(e.Message, 100)}"));
                    CloseSegment();
                    carryFrom = null;
                }
            }

            CloseSegment();
        }

        var inserts = pieces
            .Select((p, i) => MakeInsert(i, p, settings, storyboard.Seed, ltx.Continuous))
            .ToArray();

        double covered = pieces.Sum(p => p.Duration);
        progress.Report(new StageProgress(PipelineStage.Ltx, 1.0,
            ltx.Continuous
                ? $"{ordinal} clips over {inserts.Length} stretches - " +
                  $"{covered:0}s of {storyboard.Duration:0}s ({covered / Math.Max(1, storyboard.Duration):P0})"
                : $"{inserts.Length}/{totalClips} clips ready"));

        return storyboard with { Ltx = inserts };
    }

    // ------------------------------------------------------------------ planning

    /// The original shape: inserts spread over the highest-energy scenes, kept
    /// apart so they punctuate the demo rather than clumping in one passage.
    ///
    /// Two things here used to make MaxInserts close to meaningless:
    ///
    /// The spacing was `max(clipSeconds * 3, duration / (maxInserts * 2))`, and on
    /// any normal song the first term won - a 5 second clip pinned the gap at 15s
    /// however many inserts were asked for, so 6 and 12 placed exactly the same
    /// clips. The requested count now sets the spacing and the clip length only
    /// keeps two clips from touching.
    ///
    /// And each scene could host at most one clip, which capped the total at the
    /// scene count - eleven scenes could never satisfy a request for twelve - and
    /// valued a 26 second section no higher than an 8 second one.
    ///
    /// The spacing arithmetic deliberately uses the *requested* clip length rather
    /// than the length LTX will really return, because it decides which points get
    /// picked and so which prompts get hashed: switching it to the true length
    /// would move every pick by a fraction of a second and miss every clip already
    /// in the cache.
    static List<Run> PlanSparse(
        Storyboard sb, AudioAnalysis analysis, ProjectSettings settings, SongText song,
        double clipLen, int frames, int lw, int lh, IProgress<StageProgress> progress)
    {
        double clip = settings.Ltx.ClipSeconds;
        int want = Math.Max(1, settings.Ltx.MaxInserts);
        double minGap = Math.Max(clip * 1.2, sb.Duration / (want + 1));

        var candidates = new List<(StoryScene Scene, double Start)>();
        foreach (var scene in sb.Scenes)
        {
            // Land just after the scene opens so the transition is not overlapped.
            double lead = Math.Min(1.0, scene.Duration * 0.1);
            for (double start = scene.Start + lead; start + clip <= scene.End; start += minGap)
            {
                if (start + clip > sb.Duration) break;
                candidates.Add((scene, start));
            }
        }

        var picks = new List<(StoryScene Scene, double Start)>();
        foreach (var c in candidates.OrderByDescending(c => c.Scene.Energy).ThenBy(c => c.Start))
        {
            if (picks.Count >= want) break;
            if (picks.Any(p => Math.Abs(p.Start - c.Start) < minGap)) continue;
            picks.Add(c);
        }

        picks = picks.OrderBy(p => p.Start).ToList();

        // Say so when the song cannot hold what was asked for, rather than quietly
        // generating fewer and leaving it looking like a failure.
        if (picks.Count < want)
            progress.Report(new StageProgress(PipelineStage.Ltx, 0,
                $"Room for {picks.Count} of the {want} inserts requested - " +
                $"{sb.Scenes.Length} scenes across {sb.Duration / 60:0.#} min " +
                $"at {clipLen:0.##}s each"));

        var runs = new List<Run>();
        for (int i = 0; i < picks.Count; i++)
        {
            var (scene, start) = picks[i];
            var prompt = BuildPrompt(song, scene, sb, analysis, start);
            // Keyed on what the clip depicts plus its slot - not on the project
            // seed. The seed used to be in here, which made every re-plan a total
            // miss now that a run rolls a fresh one, so "Redo storyboard" would
            // regenerate every clip through ComfyUI. The prompt already carries
            // everything the seed changes about a clip's content (palette, mood,
            // the lyric at that point); the slot index only keeps two inserts that
            // happen to share a prompt - common on instrumental sections - from
            // collapsing onto one cached file.
            var key = HashKey($"{prompt}|{lw}x{lh}|{settings.Ltx.ClipSeconds}|{i}");
            runs.Add(new Run(i, scene, [new Slot(start, clipLen, prompt, key)]));
        }
        return runs;
    }

    /// Where continuous mode would put its clips, without generating any of them.
    ///
    /// The placement is the expensive decision - a bad one is only visible after an
    /// hour of ComfyUI - so it is reachable on its own.
    public IReadOnlyList<(int SceneIndex, double Start, double Duration, int Clips)> PlanCoverage(
        Storyboard sb, AudioAnalysis analysis, ProjectSettings settings,
        IProgress<StageProgress>? progress = null)
    {
        int frames = AlignFrames(settings.Ltx.ClipSeconds, settings.Fps);
        double clipLen = frames / (double)settings.Fps;
        var (rw, rh) = settings.Resolution;

        return PlanContinuous(
                sb, analysis, settings, SongText.Parse(null), clipLen, frames,
                RoundTo32(rw / 2), RoundTo32(rh / 2),
                progress ?? new Progress<StageProgress>())
            .Select(r => (r.Scene.Index, r.Slots[0].Start, r.Slots.Count * clipLen, r.Slots.Count))
            .ToList();
    }

    /// Which stretches of the video get covered end to end, and how each is tiled.
    ///
    /// The gate is EffectManifest.Coverage - the share of the frame the effect
    /// actually lights up. A clip mixed over `apollonian` (0.29: a small bright
    /// solid on black) is not a blend, it is the clip playing with a fractal in
    /// front of it, because through screen or add most of the frame has nothing to
    /// mix with and the clip simply shows through. The effects worth running video
    /// underneath are the ones that fill the picture, and the ones that don't are
    /// exactly where the run should stop for a while.
    ///
    /// Scenes carrying one of the project's images are ranked down rather than
    /// excluded: a photograph, an effect and an LTX clip at once is three pictures
    /// competing, but a long song may not have enough scenes to be fussy.
    List<Run> PlanContinuous(
        Storyboard sb, AudioAnalysis analysis, ProjectSettings settings, SongText song,
        double clipLen, int frames, int lw, int lh, IProgress<StageProgress> progress)
    {
        var ltx = settings.Ltx;
        var scenes = sb.Scenes;

        var eligible = new List<(StoryScene Scene, double Start, double End, double Score)>();
        int tooSparse = 0, tooShort = 0;

        for (int i = 0; i < scenes.Length; i++)
        {
            var s = scenes[i];
            // An effect the library no longer has cannot be judged, and dropping
            // every scene is a worse answer than trusting the plan.
            double cover = effects?.Get(s.EffectId)?.Coverage ?? 1.0;
            if (cover < ltx.MinEffectCoverage) { tooSparse++; continue; }

            // Keep off both transitions. A clip mixed over a wipe is being mixed
            // with two scenes at once, and the second of them has not started.
            double lead = Math.Max(s.TransitionDuration, Math.Min(1.0, s.Duration * 0.1));
            double tail = (i + 1 < scenes.Length ? scenes[i + 1].TransitionDuration : 0) + 0.3;
            double a = s.Start + lead;
            double b = Math.Min(s.End - tail, sb.Duration);
            if (b - a < clipLen) { tooShort++; continue; }

            bool hasImage = sb.Images?.Any(c => c.SceneIndex == s.Index) ?? false;
            double score = s.Energy
                + 0.5 * (cover - ltx.MinEffectCoverage)
                - (hasImage ? 0.25 : 0);

            eligible.Add((s, a, b, score));
        }

        // How the budget is shared out.
        //
        // Handing it to the best-scoring scenes until it runs out is the obvious
        // rule and it is the wrong one: on a real eight minute plan it spent all
        // 120 clips on the last six scenes and left the first four minutes with
        // nine seconds of video in it. The clips are meant to run *through* the
        // song, not to pick a favourite passage.
        //
        // So: every scene that can hold a run worth the name gets one, best first,
        // and only then is what is left poured back over them in proportion to how
        // much room each has. A thirty second scene fills about three times as fast
        // as a ten second one, and the ranking decides who tops up first rather
        // than who eats.
        int budget = Math.Min(ltx.MaxClips, (int)Math.Ceiling(ltx.Coverage * sb.Duration / clipLen));
        int minRun = Math.Max(1, (int)Math.Ceiling(2.5 / clipLen));

        var order = eligible
            .Select(e => (e.Scene, e.Start, Fits: (int)Math.Floor((e.End - e.Start) / clipLen), e.Score))
            .Where(e => e.Fits > 0)
            .OrderByDescending(e => e.Score).ThenBy(e => e.Scene.Index)
            .ToList();

        var take = new int[order.Count];
        int started = 0;
        foreach (var e in order)
        {
            if (budget <= 0) break;
            int seed = Math.Min(Math.Min(minRun, e.Fits), budget);
            // Below the minimum there is nothing left for a stretch, but a couple
            // of clips still beat leaving the budget on the table.
            if (seed < minRun && started > 0) break;
            take[started++] = seed;
            budget -= seed;
        }

        for (bool moved = true; budget > 0 && moved;)
        {
            moved = false;
            for (int i = 0; i < started && budget > 0; i++)
            {
                int give = Math.Min(Math.Min(Math.Max(1, order[i].Fits / 8), budget),
                                    order[i].Fits - take[i]);
                if (give <= 0) continue;
                take[i] += give;
                budget -= give;
                moved = true;
            }
        }

        var chosen = new List<(StoryScene Scene, double Start, int Count)>();
        double covered = 0;
        for (int i = 0; i < started; i++)
        {
            if (take[i] <= 0) continue;
            chosen.Add((order[i].Scene, order[i].Start, take[i]));
            covered += take[i] * clipLen;
        }

        var runs = new List<Run>();
        int ordinal = 0;
        foreach (var (scene, start, count) in chosen.OrderBy(c => c.Start))
        {
            var slots = new List<Slot>(count);
            string chain = "";
            for (int j = 0; j < count; j++)
            {
                double at = start + j * clipLen;
                var prompt = BuildPrompt(song, scene, sb, analysis, at);
                // Where the clip lands is part of its identity here, unlike sparse
                // mode: it is generated from the frame of the demo at that instant,
                // so two clips with the same prompt a second apart are not the same
                // clip. `chain` carries the previous clip's key when the run is
                // carrying its own last frame forward, because then this clip
                // genuinely depends on that one.
                var key = HashKey(
                    $"{prompt}|{lw}x{lh}|{frames}|{at.ToString("0.###", CultureInfo.InvariantCulture)}" +
                    $"|{settings.Ltx.InitMode}|{chain}");
                slots.Add(new Slot(at, clipLen, prompt, key));
                chain = settings.Ltx.Carry ? key : "";
            }
            runs.Add(new Run(ordinal++, scene, slots));
        }

        int clips = runs.Sum(r => r.Slots.Count);
        var dropped = new List<string>();
        if (tooSparse > 0) dropped.Add($"{tooSparse} too sparse to blend into");
        if (tooShort > 0) dropped.Add($"{tooShort} shorter than one clip");
        var skipNote = dropped.Count > 0 ? $"; skipped {string.Join(", ", dropped)}" : "";

        progress.Report(new StageProgress(PipelineStage.Ltx, 0,
            $"Continuous: {clips} clips of {clipLen:0.##}s ({frames} frames) over {runs.Count} of " +
            $"{scenes.Length} scenes, {covered:0}s of {sb.Duration:0}s{skipNote}"));

        if (clips >= ltx.MaxClips)
            progress.Report(new StageProgress(PipelineStage.Ltx, 0,
                $"Stopped at the {ltx.MaxClips} clip ceiling - raise it, or use longer clips, " +
                "to cover more of the song"));

        return runs;
    }

    // ---------------------------------------------------------------- generation

    async Task<string> GenerateAsync(
        ComfyClient comfy, ProjectPaths paths, ProjectSettings settings, SongText song,
        Slot slot, int frames, int lw, int lh, int ordinal, string? carryFrom,
        CancellationToken ct)
    {
        var init = await MakeInitImageAsync(comfy, paths, settings, slot, lw, lh, ordinal, carryFrom, ct);

        // Token names match the working graph exactly. It takes a %FRAMES% count
        // rather than a duration: the node behind it used to compute
        // `seconds * fps + 1` from a whole-second integer, which made sub-second
        // clips unaskable-for and quietly returned 4.83s for a 5s request anyway.
        // See AlignFrames. The graph has no audio input - LTX synthesises its own,
        // which we discard because the original MP3 is muxed over everything.
        var produced = await comfy.RunAsync("LTX2_I2V.json", new Dictionary<string, object>
        {
            ["%IMAGE%"] = comfy.StageInput(init),
            ["%PROMPT%"] = slot.Prompt,
            ["%NEGATIVE%"] = SongText.ComposeNegative(song.Negative, "text, watermark, blurry"),
            ["%WIDTH%"] = lw,
            ["%HEIGHT%"] = lh,
            ["%FRAMES%"] = frames,
            ["%FPS%"] = settings.Fps,
            // The graph's Gemma prompt rewriter. Off: it paraphrases each clip
            // independently and breaks look continuity.
            ["%ENHANCE%"] = settings.Ltx.PromptEnhance,
            ["%SEED%"] = settings.Seed + ordinal,
            ["%OUTPUT_PREFIX%"] = $"i3d_{paths.Name}_{ordinal + 1:D3}",
        }, isVideo: true, ct);

        // Named after the cache key, not its position in the plan. Position is not
        // stable across re-plans, and a clip file overwritten while a cache entry
        // still points at it serves the wrong video.
        var clipPath = Path.Combine(paths.LtxDir, $"clip_{slot.Key}.mp4");
        File.Copy(produced, clipPath, overwrite: true);
        return clipPath;
    }

    /// Init frame. "render" grabs a frame from our own 3D scene at that timestamp,
    /// so the LTX clip grows out of the demo instead of cutting to something
    /// unrelated - it costs nothing extra because we are already rendering.
    ///
    /// `carryFrom` overrides that with the previous clip's last frame, which is
    /// what makes a continuous run one take rather than a series of restarts. It
    /// also lets the run drift away from the demo and accumulate its own errors,
    /// which is why it is off by default.
    async Task<string> MakeInitImageAsync(
        ComfyClient comfy, ProjectPaths paths, ProjectSettings settings,
        Slot slot, int w, int h, int index, string? carryFrom, CancellationToken ct)
    {
        var initPath = Path.Combine(paths.KeyframeDir, $"init_{slot.Key}.png");
        Directory.CreateDirectory(paths.KeyframeDir);

        // ffmpeg cannot read and write the same path in one invocation, so a frame
        // lands in its own file and is fitted into the final one.
        var raw = Path.Combine(paths.KeyframeDir, $"init_{slot.Key}_raw.png");

        if (carryFrom is not null)
        {
            ffmpeg.ExtractLastFrame(carryFrom, raw);
            ffmpeg.FitImage(raw, initPath, w, h);
            return initPath;
        }

        if (settings.Ltx.InitMode == "render" && snapshot is not null)
        {
            var png = await snapshot(slot.Start, w, h, ct);
            await File.WriteAllBytesAsync(raw, png, ct);
            ffmpeg.FitImage(raw, initPath, w, h);
            return initPath;
        }

        var generated = await comfy.RunAsync("sdxlturbo.json", new Dictionary<string, object>
        {
            ["%PROMPT%"] = slot.Prompt,
            ["%NEGATIVE%"] = "text, watermark, blurry",
            ["%WIDTH%"] = w,
            ["%HEIGHT%"] = h,
            ["%SEED%"] = settings.Seed + index,
            ["%OUTPUT_PREFIX%"] = $"i3d_key_{index + 1:D3}",
        }, isVideo: false, ct);

        File.Copy(generated, initPath, overwrite: true);
        return initPath;
    }

    /// The one file this piece plays from. A single clip is already that file; a
    /// tiled run is joined into one so the renderer holds one <video> element per
    /// stretch instead of one per second of song.
    ///
    /// Rebuilt every time even when every clip in it was a cache hit. The clips are
    /// cached, the joining is not: which clips make up a run, and in what order,
    /// is a property of the plan, and a run file left over from a previous plan
    /// under the same name is exactly the kind of wrong that renders silently. It
    /// is seconds of ffmpeg against minutes of ComfyUI.
    string Concatenated(
        ProjectPaths paths, ProjectSettings settings,
        List<(string File, Slot Slot)> made, int index)
    {
        if (made.Count == 1) return made[0].File;

        var run = Path.Combine(paths.LtxDir, $"run_{index + 1:D3}.mp4");
        ffmpeg.Concat(made.Select(m => m.File).ToList(), run, settings.Fps);
        return run;
    }

    // ------------------------------------------------------------------ inserts

    LtxInsert MakeInsert(int index, Piece piece, ProjectSettings settings, int seed, bool continuous)
    {
        // Deterministic per-run blend choice, biased by scene energy: hot scenes
        // get additive/screen (they bloom), calmer ones get multiply/overlay.
        // Seeded from the run rather than the insert so a run split by a failed
        // clip does not change operator halfway through.
        var rng = new Random(seed * 7919 + piece.Run);
        var pool = piece.Scene.Energy > 0.65
            ? new[] { "screen", "add", "difference", "xor" }
            : ["multiply", "overlay", "screen"];
        var blend = pool[rng.Next(pool.Length)];

        return new LtxInsert(
            Index: index,
            Start: piece.Start,
            Duration: piece.Duration,
            ClipFile: Path.GetFileName(piece.File),
            Blend: blend,
            Opacity: Opacity(piece, settings.Ltx.Strength, continuous, rng),
            Prompt: "",
            InitMode: settings.Ltx.InitMode);
    }

    /// The mix expression written into the insert, 0..1.
    ///
    /// Written in absolute seconds rather than in `clipT`, which is normalised
    /// across the whole insert: a fade of "the first 0.6 of clipT" is 0.6 of a
    /// five second clip and eighteen seconds of a thirty second run.
    static string Opacity(Piece p, double strength, bool continuous, Random rng)
    {
        double fade = Math.Clamp(p.Duration * 0.25, 0.15, 0.9);
        double a = p.Start, b = p.Start + p.Duration;

        // Fade in and out so a clip never pops; peaks with the music. The 0.61/0.39
        // split is what every insert used before strength was a setting, so a
        // project left at the default 0.9 renders exactly as it did.
        var env = $"smoothstep({N(a)},{N(a + fade)},t)*smoothstep({N(b)},{N(b - fade)},t)";
        var level = $"({N(strength * 0.61)}+{N(strength * 0.39)}*rms)";

        if (!continuous) return $"{env}*{level}";

        // A run held at one strength for half a minute stops being an effect and
        // becomes the picture. A swell too slow to count keeps it moving under the
        // beat-to-beat response without ever announcing itself; the phase is per
        // run so two neighbouring stretches do not breathe in step.
        double phase = rng.NextDouble() * Math.Tau;
        return $"clamp({env}*{level}*(0.78+0.22*sin(t*0.37+{N(phase)})),0,1)";
    }

    // ------------------------------------------------------------------- helpers

    /// The frame count to ask LTX for, for a clip of roughly `seconds`.
    ///
    /// Its VAE compresses time by 8, so the only lengths it can return are
    /// 8k+1 frames; ask for anything else and ComfyUI floors the latent and hands
    /// back a shorter clip than requested. That is where the long-standing "5s
    /// request, 4.83s clip" came from - 151 frames asked for, 145 returned - and
    /// why the storyboard used to claim a duration the file did not have.
    ///
    /// Rounded down rather than to nearest so a clip can never overrun the slot it
    /// was tiled into, which is what keeps a continuous run gapless and in step.
    /// The floor of 9 frames is the shortest thing LTX makes anything of at all:
    /// two latent frames, 0.3s at 30fps.
    public static int AlignFrames(double seconds, int fps)
    {
        int k = (int)Math.Floor((Math.Max(0.01, seconds) * fps - 1) / 8.0);
        return Math.Max(9, k * 8 + 1);
    }

    static int RoundTo32(double v) => Math.Max(32, (int)(Math.Round(v / 32.0) * 32));

    static string N(double v) => v.ToString("0.###", CultureInfo.InvariantCulture);

    static string HashKey(string raw) =>
        Convert.ToHexString(SHA256.HashData(Encoding.UTF8.GetBytes(raw)))[..16];

    static string BuildPrompt(
        SongText song, StoryScene scene, Storyboard sb, AudioAnalysis analysis, double t)
    {
        var section = analysis.Sections.FirstOrDefault(s => t >= s.Start && t < s.End);
        var lyric = section?.Lyrics.FirstOrDefault() ?? "";

        // Same three-layer composition Mp3ToVid uses: author directives, then the
        // storyboard's global look, then this beat's own colour.
        var style = SongText.ComposeStyle(
            song.Style,
            $"{sb.Palette} palette, abstract demoscene visual, {sb.Mood}",
            scene.Energy > 0.7 ? "harsh high contrast, intense" : "soft, restrained");

        var subject = string.IsNullOrWhiteSpace(lyric)
            ? "abstract flowing forms, geometric light structures"
            : lyric;

        return $"{subject}. {style}".Trim();
    }

    static Dictionary<string, string> LoadCache(ProjectPaths paths)
    {
        if (!File.Exists(paths.LtxPromptsFile)) return [];
        try
        {
            return JsonSerializer.Deserialize<Dictionary<string, string>>(
                File.ReadAllText(paths.LtxPromptsFile)) ?? [];
        }
        catch (JsonException) { return []; }
    }

    static void SaveCache(ProjectPaths paths, Dictionary<string, string> cache) =>
        File.WriteAllText(paths.LtxPromptsFile,
            JsonSerializer.Serialize(cache, new JsonSerializerOptions { WriteIndented = true }));

    static string Trunc(string s, int n) => s.Length <= n ? s : s[..n] + "...";
}
